// Topic: Arithmetic operators
// Definition: Arithmetic operators perform mathematical calculations.
// Explanation: +, -, *, /, and % are common arithmetic operators.

#include <iostream> // Required for output.
using namespace std; // Uses standard namespace.

int main() { // Program starts here.
    int a = 10; // First number.
    int b = 3; // Second number.

    cout << "Addition: " << a + b << endl; // Adds two numbers.
    cout << "Subtraction: " << a - b << endl; // Subtracts b from a.
    cout << "Multiplication: " << a * b << endl; // Multiplies two numbers.
    cout << "Division: " << a / b << endl; // Gives quotient because both are integers.
    cout << "Remainder: " << a % b << endl; // Gives remainder.

    return 0; // Ends the program.
}

