// Topic: for loop
// Definition: A for loop repeats code when the number of repetitions is known.
// Explanation: It has initialization, condition, and update in one line.

#include <iostream> // Gives cout.
using namespace std; // Uses standard names.

int main() { // Program starts here.
    for (int i = 1; i <= 5; i++) { // Starts at 1, runs until 5, increases by 1.
        cout << i << " "; // Prints current value.
    }

    return 0; // Ends successfully.
}

