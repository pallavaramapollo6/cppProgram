// Topic: Function with no argument and no return
// Definition: This function takes no input and sends no value back.
// Explanation: It is used for simple repeated actions.

#include <iostream> // Gives cout.
using namespace std; // Uses standard names.

void greet() { // void means no return value.
    cout << "Welcome to C++" << endl; // Function work.
}

int main() { // Program starts here.
    greet(); // Calls the function.
    return 0; // Ends successfully.
}

