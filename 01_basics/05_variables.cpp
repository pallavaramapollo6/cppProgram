// Topic: Variables
// Definition: A variable is a named memory location used to store a value.
// Explanation: Variable names should be meaningful and cannot start with a digit.

#include <iostream> // Gives cout.
using namespace std; // Uses standard names.

int main() { // Program starts here.
    int firstNumber = 10; // Stores first number.
    int secondNumber = 20; // Stores second number.
    int sum = firstNumber + secondNumber; // Stores addition result.

    cout << "Sum: " << sum << endl; // Prints result.
    return 0; // Ends successfully.
}

