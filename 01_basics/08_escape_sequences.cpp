// Topic: Escape sequences
// Definition: Escape sequences are special characters written with backslash.
// Explanation: \n gives new line and \t gives tab space.

#include <iostream> // Gives cout.
using namespace std; // Uses standard names.

int main() { // Program starts here.
    cout << "Name:\tRavi\n"; // \t adds tab and \n moves to new line.
    cout << "Course:\tC++\n"; // Prints another line.
    return 0; // Ends successfully.
}

