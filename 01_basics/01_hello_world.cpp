// Topic: Basic syntax and first C++ program
// Definition: C++ is a high-level programming language used to create fast and reusable programs.
// Explanation: Every C++ program starts execution from the main() function.

#include <iostream> // Gives input and output features like cout and cin.
using namespace std; // Allows us to write cout instead of std::cout.

int main() { // main() is the starting point of the program.
    cout << "Hello, World!" << endl; // cout prints text on the screen; endl moves to a new line.
    return 0; // return 0 means the program finished successfully.
}

